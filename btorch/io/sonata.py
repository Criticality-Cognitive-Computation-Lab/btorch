"""Share SONATA file mechanics without interpreting network Modules."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Generic, Literal, Protocol, TypeVar

import numpy as np
import torch
from torch import nn

from btorch.models.kernels.options import KernelOptions
from btorch.utils._optional import require


NetworkT = TypeVar("NetworkT", bound=nn.Module)


@dataclass(frozen=True)
class SonataImport(Generic[NetworkT]):
    """Return a network and its scalar timestep without changing environ.

    Attributes:
        network: Network constructed by the network-specific adapter.
        dt: Simulation timestep in milliseconds for this mapping.
    """

    network: NetworkT
    dt: float


class SonataNetworkIO(Protocol[NetworkT]):
    """Specify calls shared by network-specific SONATA implementations.

    An adapter owns traversal, ID mapping, units, model construction and
    its supported scope. This interface does not define a network
    schema. Export returns the circuit config path; import leaves memory
    initialization and setting environ to the caller. Runtime
    checkpoints are separate artifacts.
    """

    def export_network(self, network: NetworkT, directory: Path, *, dt: float) -> Path:
        """Export a supported network to a SONATA circuit config."""
        ...

    def import_network(
        self,
        circuit_config: Path,
        *,
        device: torch.device | str = "cpu",
        dtype: torch.dtype | None = None,
        backend: str | KernelOptions = "torch",
    ) -> SonataImport[NetworkT]:
        """Build the network described by this adapter's mapping."""
        ...


@dataclass(frozen=True)
class SonataPopulation:
    """Hold one SONATA population with one attribute group.

    Attributes:
        columns: Core ID/type columns and per-element ordinary attributes.
        dynamics: Per-element dynamics attributes, stored in dynamics_params.
        source: Source population name for edges.
        target: Target population name for edges.
    """

    columns: dict[str, np.ndarray]
    dynamics: dict[str, np.ndarray] = field(default_factory=dict)
    source: str | None = None
    target: str | None = None


def write_population(
    path: Path,
    name: str,
    data: SonataPopulation,
    *,
    kind: Literal["nodes", "edges"],
) -> None:
    """Write a single-group population using SONATA HDF5 conventions.

    The caller supplies node_id/node_type_id for nodes, or
    source_node_id, target_node_id/edge_type_id for edges. Other columns
    become group attributes. This helper neither traverses Modules nor
    converts model units or IDs.
    """
    h5py = require("h5py", extra="io")
    if kind not in ("nodes", "edges"):
        raise ValueError("kind must be nodes or edges")
    core = (
        ("node_id", "node_type_id")
        if kind == "nodes"
        else ("source_node_id", "target_node_id", "edge_type_id")
    )
    if not name or "/" in name or any(key not in data.columns for key in core):
        raise ValueError("Supply a population name and all core ID/type columns")
    count = len(data.columns[core[0]])
    arrays = {**data.columns, **data.dynamics}
    if any(
        np.asarray(value).ndim != 1 or len(value) != count for value in arrays.values()
    ):
        raise ValueError("Population attributes must be 1-D with one value per element")
    if any(
        np.asarray(data.columns[key]).dtype.kind not in "iu"
        or np.any(np.asarray(data.columns[key]) < 0)
        for key in core
    ):
        raise ValueError("Core IDs must be nonnegative integer arrays")
    prefix = "node" if kind == "nodes" else "edge"
    reserved = {*core, f"{prefix}_group_id", f"{prefix}_group_index"}
    if reserved.intersection(data.columns) != set(core):
        raise ValueError("Group IDs/indices are generated by this single-group helper")
    if kind == "edges" and (data.source is None or data.target is None):
        raise ValueError("Edge populations require source and target names")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "w") as file:
        file.attrs["magic"] = np.uint32(0x0A7A)
        file.attrs["version"] = np.array([0, 1], dtype=np.uint32)
        population = file.create_group(f"{kind}/{name}")
        for key in core:
            dataset = population.create_dataset(key, data=data.columns[key])
            if key in ("source_node_id", "target_node_id"):
                dataset.attrs["node_population"] = (
                    data.source if key == "source_node_id" else data.target
                )
        population.create_dataset(f"{prefix}_group_id", data=np.zeros(count, np.uint32))
        population.create_dataset(
            f"{prefix}_group_index", data=np.arange(count, dtype=np.uint64)
        )
        group = population.create_group("0")
        for key, values in data.columns.items():
            if key not in core:
                group.create_dataset(key, data=values)
        dynamics = group.create_group("dynamics_params")
        for key, values in data.dynamics.items():
            dynamics.create_dataset(key, data=values)


def read_population(
    path: Path, name: str, *, kind: Literal["nodes", "edges"]
) -> SonataPopulation:
    """Read a single-group population into original element order.

    Reject other layouts rather than silently discard their attributes.
    A network-specific importer can use libSONATA for more general
    files.
    """
    h5py = require("h5py", extra="io")
    if kind not in ("nodes", "edges"):
        raise ValueError("kind must be nodes or edges")
    prefix = "node" if kind == "nodes" else "edge"
    with h5py.File(path, "r") as file:
        if file.attrs.get("magic") != 0x0A7A or not np.array_equal(
            file.attrs.get("version"), [0, 1]
        ):
            raise ValueError("Expected SONATA magic and version 0.1")
        population = file[f"{kind}/{name}"]
        groups = population[f"{prefix}_group_id"][:]
        index = population[f"{prefix}_group_index"][:]
        if np.any(groups != 0) or sorted(index.tolist()) != list(range(len(index))):
            raise ValueError("Expected a single group with a complete row mapping")
        columns = {
            key: value[:]
            for key, value in population.items()
            if isinstance(value, h5py.Dataset)
            and key not in (f"{prefix}_group_id", f"{prefix}_group_index")
        }
        group = population["0"]
        columns.update(
            {
                key: value[:][index]
                for key, value in group.items()
                if isinstance(value, h5py.Dataset)
            }
        )
        dynamics = {
            key: value[:][index]
            for key, value in group.get("dynamics_params", {}).items()
        }
        names = []
        for key in ("source_node_id", "target_node_id"):
            value = (
                population[key].attrs["node_population"] if kind == "edges" else None
            )
            names.append(value.decode() if isinstance(value, bytes) else value)
    return SonataPopulation(columns, dynamics, *names)


def write_edge_indices(
    path: Path, population: str, *, source_count: int, target_count: int
) -> None:
    """Build SONATA lookup indices through libSONATA's native
    implementation."""
    try:
        import libsonata
    except ImportError as error:
        raise ImportError("Install libsonata to build SONATA edge indices") from error
    libsonata.EdgePopulation.write_indices(
        str(path), population, source_count, target_count
    )
    # pySONATA uses the singular spelling; libSONATA writes the plural one.
    # Hard links make both readers work without duplicating the lookup tables.
    h5py = require("h5py", extra="io")
    with h5py.File(path, "r+") as file:
        indices = file[f"edges/{population}/indices"]
        for direction in ("source_to_target", "target_to_source"):
            group = indices[direction]
            if "node_id_to_range" not in group:
                group["node_id_to_range"] = group["node_id_to_ranges"]
